function esc(v) {
  return v.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

for (const [lang, map] of Object.entries(extras)) {
  const marker = `const Map<String, String> _${lang}Extra = {`;
  const start = s.indexOf(marker);
  if (start < 0) throw new Error('missing ' + lang);
  const endBrace = s.indexOf('\n};', start);
  if (endBrace < 0) throw new Error('no end ' + lang);
  const insert = Object.entries(map)
    .map(([k, v]) => `  '${k}': '${esc(v)}',`)
    .join('\n');
  // Insert before closing };
  s = s.slice(0, endBrace) + '\n' + insert + s.slice(endBrace);
}

fs.writeFileSync(file, s);
